import client from './client'

export const ReminderCategory = {
  StaleApplication: 0,
  ExpiringDocument: 1,
  UpcomingInterview: 2,
  MissingAction: 3,
  ContactFollowUp: 4,
  General: 5,
} as const
export type ReminderCategory = typeof ReminderCategory[keyof typeof ReminderCategory]

export const ReminderCategoryLabels: Record<number, string> = {
  0: 'Stale Application',
  1: 'Expiring Document',
  2: 'Upcoming Interview',
  3: 'Missing Action',
  4: 'Contact Follow-Up',
  5: 'General Reminder',
}

export const ReminderSeverity = {
  Low: 0,
  Medium: 1,
  High: 2,
  Critical: 3,
} as const
export type ReminderSeverity = typeof ReminderSeverity[keyof typeof ReminderSeverity]

export const ReminderSeverityLabels: Record<number, string> = {
  0: 'Low Advisory',
  1: 'Medium Action',
  2: 'High Priority',
  3: 'Critical / Urgent',
}

export interface Reminder {
  id: string
  category: number
  categoryName: string
  severity: number
  severityName: string
  title: string
  message: string
  entityType?: string
  entityId?: string
  actionUrl?: string
  dueDate?: string
  isDismissed: boolean
  dismissedAt?: string
  isSnoozed: boolean
  snoozedUntil?: string
  isAutoGenerated: boolean
  createdAt: string
  updatedAt: string
}

export interface FollowUpSummary {
  totalActive: number
  staleApplicationsCount: number
  expiringDocumentsCount: number
  upcomingInterviewsCount: number
  missingActionsCount: number
  contactFollowUpsCount: number
  highOrCriticalCount: number
}

export interface CreateCustomReminderRequest {
  title: string
  message: string
  category?: number
  severity?: number
  actionUrl?: string
  dueDate?: string
}

export interface FollowUpFilterParams {
  category?: number
  severity?: number
  includeDismissed?: boolean
  includeSnoozed?: boolean
}

export const followUpApi = {
  getAll: async (params?: FollowUpFilterParams): Promise<Reminder[]> => {
    const response = await client.get<Reminder[]>('/followup', { params })
    return response.data
  },

  getSummary: async (): Promise<FollowUpSummary> => {
    const response = await client.get<FollowUpSummary>('/followup/summary')
    return response.data
  },

  scan: async (): Promise<{ newRemindersCount: number }> => {
    const response = await client.post<{ newRemindersCount: number }>('/followup/scan')
    return response.data
  },

  createCustom: async (data: CreateCustomReminderRequest): Promise<Reminder> => {
    const response = await client.post<Reminder>('/followup/custom', data)
    return response.data
  },

  dismiss: async (id: string): Promise<void> => {
    await client.patch(`/followup/${id}/dismiss`)
  },

  snooze: async (id: string, days: number): Promise<void> => {
    await client.patch(`/followup/${id}/snooze`, { days })
  },

  delete: async (id: string): Promise<void> => {
    await client.delete(`/followup/${id}`)
  },
}

