using AutoMapper;
using CareerOS.Application.Features.FollowUp.DTOs;
using CareerOS.Domain.Entities;
using CareerOS.Domain.Enums;
using CareerOS.Domain.Interfaces;
using FluentValidation;
using MediatR;

namespace CareerOS.Application.Features.FollowUp.Commands.CreateCustomReminder;

public record CreateCustomReminderCommand : IRequest<ReminderDto>
{
    public string Title { get; init; } = string.Empty;
    public string Message { get; init; } = string.Empty;
    public ReminderCategory Category { get; init; } = ReminderCategory.General;
    public ReminderSeverity Severity { get; init; } = ReminderSeverity.Medium;
    public string? ActionUrl { get; init; }
    public DateTime? DueDate { get; init; }
}

public class CreateCustomReminderCommandHandler : IRequestHandler<CreateCustomReminderCommand, ReminderDto>
{
    private readonly IUnitOfWork _uow;
    private readonly IMapper _mapper;

    public CreateCustomReminderCommandHandler(IUnitOfWork uow, IMapper mapper)
    {
        _uow = uow;
        _mapper = mapper;
    }

    public async Task<ReminderDto> Handle(CreateCustomReminderCommand request, CancellationToken cancellationToken)
    {
        var item = ReminderItem.Create(
            category: request.Category,
            severity: request.Severity,
            title: request.Title,
            message: request.Message,
            actionUrl: request.ActionUrl,
            dueDate: request.DueDate,
            isAutoGenerated: false);

        await _uow.Reminders.AddAsync(item, cancellationToken);
        await _uow.SaveChangesAsync(cancellationToken);

        return _mapper.Map<ReminderDto>(item);
    }
}

public class CreateCustomReminderCommandValidator : AbstractValidator<CreateCustomReminderCommand>
{
    public CreateCustomReminderCommandValidator()
    {
        RuleFor(x => x.Title)
            .NotEmpty().WithMessage("Title is required.")
            .MaximumLength(200).WithMessage("Title cannot exceed 200 characters.");
    }
}
