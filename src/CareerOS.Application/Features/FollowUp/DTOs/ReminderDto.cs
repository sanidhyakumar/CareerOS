using CareerOS.Domain.Enums;

namespace CareerOS.Application.Features.FollowUp.DTOs;

public class ReminderDto
{
    public Guid Id { get; set; }
    public ReminderCategory Category { get; set; }
    public string CategoryName => Category.ToString();
    public ReminderSeverity Severity { get; set; }
    public string SeverityName => Severity.ToString();

    public string Title { get; set; } = string.Empty;
    public string Message { get; set; } = string.Empty;

    public string? EntityType { get; set; }
    public Guid? EntityId { get; set; }
    public string? ActionUrl { get; set; }

    public DateTime? DueDate { get; set; }

    public bool IsDismissed { get; set; }
    public DateTime? DismissedAt { get; set; }

    public bool IsSnoozed { get; set; }
    public DateTime? SnoozedUntil { get; set; }

    public bool IsAutoGenerated { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }
}

public class FollowUpSummaryDto
{
    public int TotalActive { get; set; }
    public int StaleApplicationsCount { get; set; }
    public int ExpiringDocumentsCount { get; set; }
    public int UpcomingInterviewsCount { get; set; }
    public int MissingActionsCount { get; set; }
    public int ContactFollowUpsCount { get; set; }
    public int HighOrCriticalCount { get; set; }
}

