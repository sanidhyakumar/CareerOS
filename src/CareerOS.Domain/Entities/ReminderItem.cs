using CareerOS.Domain.Common;
using CareerOS.Domain.Enums;

namespace CareerOS.Domain.Entities;

public class ReminderItem : BaseEntity
{
    public Guid? CareerProfileId { get; set; }
    public CareerProfile? CareerProfile { get; set; }

    public ReminderCategory Category { get; set; } = ReminderCategory.General;
    public ReminderSeverity Severity { get; set; } = ReminderSeverity.Medium;

    public string Title { get; set; } = string.Empty;
    public string Message { get; set; } = string.Empty;

    public string? EntityType { get; set; }  // "Application", "Document", "Interview", "Contact", "Job"
    public Guid? EntityId { get; set; }
    public string? ActionUrl { get; set; }   // e.g. "/applications", "/documents"

    public DateTime? DueDate { get; set; }

    public bool IsDismissed { get; set; }
    public DateTime? DismissedAt { get; set; }

    public bool IsSnoozed { get; set; }
    public DateTime? SnoozedUntil { get; set; }

    public bool IsAutoGenerated { get; set; } = true;
    public string? DeduplicationKey { get; set; } // Prevents re-creating duplicate auto-reminders

    public ReminderItem() { }

    public static ReminderItem Create(
        ReminderCategory category,
        ReminderSeverity severity,
        string title,
        string message,
        string? entityType = null,
        Guid? entityId = null,
        string? actionUrl = null,
        DateTime? dueDate = null,
        bool isAutoGenerated = true,
        string? deduplicationKey = null)
    {
        if (string.IsNullOrWhiteSpace(title)) throw new ArgumentException("Title is required.", nameof(title));

        return new ReminderItem
        {
            Category = category,
            Severity = severity,
            Title = title.Trim(),
            Message = message?.Trim() ?? string.Empty,
            EntityType = entityType?.Trim(),
            EntityId = entityId,
            ActionUrl = actionUrl?.Trim(),
            DueDate = dueDate,
            IsAutoGenerated = isAutoGenerated,
            DeduplicationKey = deduplicationKey
        };
    }

    public void Dismiss()
    {
        IsDismissed = true;
        DismissedAt = DateTime.UtcNow;
        UpdatedAt = DateTime.UtcNow;
    }

    public void Snooze(TimeSpan duration)
    {
        IsSnoozed = true;
        SnoozedUntil = DateTime.UtcNow.Add(duration);
        UpdatedAt = DateTime.UtcNow;
    }

    public void Unsnooze()
    {
        IsSnoozed = false;
        SnoozedUntil = null;
        UpdatedAt = DateTime.UtcNow;
    }
}
